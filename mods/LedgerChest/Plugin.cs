using System.Collections.Generic;
using BepInEx;
using BepInEx.Configuration;
using HarmonyLib;
using UnityEngine;

// Its pieces reload while you play: they stay registered across a reload and the ones standing get the new copy (Shared/PieceReload.cs).
[assembly: System.Reflection.AssemblyMetadata("ClaudeTools.Reload", "world")]

namespace LedgerChest
{
    /// <summary>
    /// The Ledger Chest: a strongbox you build that is a chest of its own and, when you open it, shows everything in every chest around it
    /// in one list, with a search. Click an item to take it out of whichever chest holds it.
    ///
    /// Split across files: Plugin.cs (setup, registering the piece), ModelData.cs (the look, generated by tools/modelkit/ledgerchest.py),
    /// ModelBuilder.cs and Look.cs (turning it into game objects), Icon.cs (the build-menu picture), Stores.cs (finding the chests and
    /// taking from them), Ledger.cs (the ledger, in the chest window's place), GameUi.cs (the game's own interface parts it is built from:
    /// Claude Tools' template).
    /// </summary>
    [BepInPlugin(Guid, Name, Version)]
    public class Plugin : BaseUnityPlugin
    {
        public const string Guid = "com.quad.ledgerchest";
        public const string OldGuid = "com.dhack.ledgerchest"; // (its id until 2026-10: settings move over by themselves, see Shared/Migration.cs)
        public const string Name = "LedgerChest";
        public const string Version = "1.2.3";
        public const string PiecePrefab = "piece_ledgerchest";

        internal static Plugin Instance;
        internal static ConfigEntry<float> Radius, Scale;
        internal static DHack.Shared.ServerSettings Synced;   // the cost the server decides in multiplayer (and whether it has the mod)
        internal static ConfigEntry<string> Cost;
        internal static BepInEx.Logging.ManualLogSource Log;
        private static bool _tellNoServer;   // the server hasn't the mod: say so once the player is in the world

        /// <summary>What a Ledger Chest costs before anyone changes it.</summary>
        internal const string DefaultCost = "Wood:10, FineWood:4, LeatherScraps:4, Resin:2";

        private static GameObject _holder, _prefab;
        private Harmony _harmony;
        internal readonly Ledger Ledger = new Ledger();

        private void Awake()
        {
            DHack.Shared.Migration.FromOldGuid(this, OldGuid); // first: before any setting is read
            DHack.Shared.Translations.Load(this);   // translations/*.json: its words in the player's language
            Instance = this;
            Log = Logger;
            Synced = new DHack.Shared.ServerSettings(Guid, Config, Logger);
            Radius = Config.Bind("Ledger", "Radius", 30f, new ConfigDescription("How far from the Ledger Chest (metres) the chests it lists can be.", new AcceptableValueRange<float>(5f, 60f)));
            Scale = Config.Bind("Ledger", "Scale", 1f, new ConfigDescription("Size of the category buttons and notes under the ledger.", new AcceptableValueRange<float>(0.6f, 2f)));
            Cost = Synced.Bind("Building", "Cost", DefaultCost, "What a Ledger Chest costs to build with the hammer (at a workbench). " + DHack.Shared.Costs.Help);
            Cost.SettingChanged += (s, e) => ApplyCost();
            Synced.ServerChanged += () => _tellNoServer = Synced.Server == DHack.Shared.ServerSettings.ServerMod.Missing;
            _harmony = new Harmony(Guid);
            _harmony.PatchAll();
            if (ZNetScene.instance != null) Register(ZNetScene.instance); // hot reload while in a world
            Logger.LogInfo($"{Name} {Version} loaded");
        }

        private void OnDestroy()
        {
            try { _claudeTools?.GetType().GetMethod("UnregisterAll", System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static)?.Invoke(null, new object[] { Name }); } catch { }
            Ledger.Close();
            Ledger.Destroy();
            GameUi.Destroy();
            DHack.Shared.Translations.Unload();
            if (Instance == this) Instance = null;
            _harmony?.UnpatchSelf();
            Unregister();
            Synced?.Dispose();
        }

        private void Update()
        {
            Synced?.Update();
            if (_tellNoServer && Player.m_localPlayer != null)
            {
                _tellNoServer = false;
                Player.m_localPlayer.Message(MessageHud.MessageType.Center, "$ledgerchest_server_missing");
            }
            Ledger.Tick();
            ClaudeLink();
        }

        // ---- Claude Tools (if installed): a "ledgers" command reporting each Ledger Chest's state (for finding problems) ----
        private BaseUnityPlugin _claudeTools;
        private float _nextClaudeCheck;

        private void ClaudeLink()
        {
            if (Time.unscaledTime < _nextClaudeCheck) return;
            _nextClaudeCheck = Time.unscaledTime + 5f;
            BaseUnityPlugin found = BepInEx.Bootstrap.Chainloader.PluginInfos.TryGetValue("com.quad.claudetools", out PluginInfo info) ? info.Instance : null;
            if (found == _claudeTools) return;
            _claudeTools = found;
            if (found == null) return;
            var register = found.GetType().GetMethod("RegisterCommand", System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static);
            System.Func<string[], System.Action<Newtonsoft.Json.Linq.JObject>, System.Action<string>, System.Collections.IEnumerator> cmd = (a, output, error) =>
            {
                var list = new Newtonsoft.Json.Linq.JArray();
                foreach (Container c in Object.FindObjectsByType<Container>(FindObjectsInactive.Include, FindObjectsSortMode.None))
                {
                    if (c == null || !c.gameObject.name.StartsWith(PiecePrefab)) continue;
                    ZNetView v = c.GetComponent<ZNetView>();
                    var comps = new Newtonsoft.Json.Linq.JArray();
                    foreach (Component k in c.GetComponents<Component>()) comps.Add(k == null ? "(missing script)" : k.GetType().Name + (k is Behaviour b && !b.enabled ? " (off)" : ""));
                    var cols = new Newtonsoft.Json.Linq.JArray();
                    foreach (Collider col in c.GetComponentsInChildren<Collider>(true)) cols.Add($"{col.name} {LayerMask.LayerToName(col.gameObject.layer)} {(col.enabled && col.gameObject.activeInHierarchy ? "on" : "OFF")}");
                    list.Add(new Newtonsoft.Json.Linq.JObject
                    {
                        ["name"] = c.gameObject.name, ["active"] = c.gameObject.activeInHierarchy, ["position"] = c.transform.position.ToString("F1"),
                        ["nviewValid"] = v != null && v.IsValid(), ["owner"] = v != null && v.IsValid() ? v.GetZDO().GetOwner().ToString() : "-", ["mine"] = v != null && v.IsValid() && v.IsOwner(),
                        ["inUse"] = c.IsInUse(), ["components"] = comps, ["colliders"] = cols, ["isPrefabCopy"] = c.transform.parent != null && c.transform.parent.name.EndsWith("Prefabs"),
                    });
                }
                output(new Newtonsoft.Json.Linq.JObject { ["ledgers"] = list });
                return null;
            };
            register?.Invoke(null, new object[] { Name, "ledgers", "ledgers: every Ledger Chest object: active, its network view, owner, components, colliders", cmd });
            System.Func<string[], System.Action<Newtonsoft.Json.Linq.JObject>, System.Action<string>, System.Collections.IEnumerator> kinds = (a, output, error) =>
            {
                var by = new Newtonsoft.Json.Linq.JObject();
                if (ObjectDB.instance != null)
                    foreach (GameObject go in ObjectDB.instance.m_items)
                    {
                        ItemDrop d = go != null ? go.GetComponent<ItemDrop>() : null;
                        if (d == null) continue;
                        string k = Kinds.Of(d.m_itemData.m_shared);
                        if (by[k] == null) by[k] = new Newtonsoft.Json.Linq.JArray();
                        ((Newtonsoft.Json.Linq.JArray)by[k]).Add($"{d.m_itemData.m_shared.m_name} ({Localization.instance.Localize(d.m_itemData.m_shared.m_name)})");
                    }
                output(new Newtonsoft.Json.Linq.JObject { ["kinds"] = by });
                return null;
            };
            register?.Invoke(null, new object[] { Name, "ledgerkinds", "ledgerkinds: every item in the game under the ledger button it shows under", kinds });
        }

        /// <summary>A Ledger Chest (by its name: one built before a reload of this mod carries the old copy's marker).</summary>
        internal static bool IsLedger(Component c) => c != null && c.gameObject.name.StartsWith(PiecePrefab, System.StringComparison.Ordinal);

        internal static void Register(ZNetScene scene)
        {
            GameObject source = scene.GetPrefab("piece_chest_wood");
            GameObject hammer = scene.GetPrefab("Hammer"); // items are in the scene too, and ObjectDB may not be awake yet
            GameObject bench = scene.GetPrefab("piece_workbench");
            if (source == null || hammer == null) { Debug.LogWarning(Name + ": chest or hammer prefab not found"); return; }

            if (_prefab == null)
            {
                _holder = new GameObject(Name + "Prefabs");
                _holder.SetActive(false); // keeps the copy from waking up as a real object
                Object.DontDestroyOnLoad(_holder);
                try { Look.Harvest(scene, source.GetComponentInChildren<Renderer>(true).sharedMaterial); }
                catch (System.Exception e) { Debug.LogWarning($"{Name}: could not find the game's materials: {e.Message}"); }
                _prefab = Make(source, bench != null ? bench.GetComponent<CraftingStation>() : null);
            }

            // registered in place of an older copy's (a hot reload while playing), and the chests standing get this copy's marker
            // (what is in them is the game's own Container, untouched)
            DHack.Shared.PieceReload.ReplacePrefab(scene, _prefab, hammer.GetComponent<ItemDrop>().m_itemData.m_shared.m_buildPieces);
            Synced.NeedsServer(_prefab);   // not in the build menu on a server without the mod (it would delete the chest and what is in it)
            int swapped = DHack.Shared.PieceReload.Reattach(scene, _prefab);
            if (swapped > 0) Debug.Log($"{Name}: {swapped} Ledger Chest(s) in the world now run this copy");
        }

        /// <summary>The cost setting (the server's in multiplayer) on the piece. One that can't be read keeps the last good cost.</summary>
        internal static void ApplyCost()
        {
            Piece piece = _prefab != null ? _prefab.GetComponent<Piece>() : null;
            if (piece != null) DHack.Shared.Costs.Apply(piece, Cost.Value, Log);
        }

        private static GameObject Make(GameObject source, CraftingStation workbench)
        {
            GameObject go = Object.Instantiate(source, _holder.transform);
            go.name = PiecePrefab;

            // It stays a chest (the game's own: opening, saving, multiplayer), a bigger one, with its own name.
            Container chest = go.GetComponent<Container>();
            chest.m_name = "$ledgerchest_piece";
            chest.m_width = 6;
            chest.m_height = 3;

            int layer = LayerMask.NameToLayer("piece");
            if (layer < 0) layer = go.layer;
            foreach (Renderer r in go.GetComponentsInChildren<Renderer>(true)) r.enabled = false; // hide the wooden chest
            foreach (Collider c in go.GetComponentsInChildren<Collider>(true)) Object.DestroyImmediate(c); // and its hitbox
            var hit = new GameObject("Hitbox") { layer = layer };
            hit.transform.SetParent(go.transform, false);
            var box = hit.AddComponent<BoxCollider>();
            box.center = new Vector3(0f, 0.45f, 0f);
            box.size = new Vector3(1.38f, 0.9f, 0.82f);
            var top = hit.AddComponent<BoxCollider>(); // the stand and the book on the lid
            top.center = new Vector3(-0.12f, 0.98f, 0.05f);
            top.size = new Vector3(0.66f, 0.42f, 0.46f);

            // The look can fail (a game update renames a material), but the piece must still be registered: without it the host deletes
            // every placed Ledger Chest, with what is in it. Then it keeps the wooden chest's look.
            try { ModelBuilder.Build(go.transform, ModelData.Parts, go.layer); }
            catch (System.Exception e)
            {
                Debug.LogWarning($"{Name}: could not build the Ledger Chest's look, it keeps the wooden chest's: {e.Message}");
                foreach (Renderer r in go.GetComponentsInChildren<Renderer>(true)) r.enabled = true;
            }

            // snap points on the corners of its base, handles included (the wooden chest has none): it lines up with floor corners, wall
            // ends and the chests beside it
            DHack.Shared.SnapPoints.Clear(go);
            DHack.Shared.SnapPoints.Box(go, new Vector3(-0.76f, 0f, -0.42f), new Vector3(0.76f, 0f, 0.42f));

            Piece piece = go.GetComponent<Piece>();
            piece.m_name = "$ledgerchest_piece";
            piece.m_description = "$ledgerchest_piece_desc";
            piece.m_category = Piece.PieceCategory.Furniture;
            piece.m_usage = Piece.UsageTagFlags.Storage | Piece.UsageTagFlags.Furniture;   // the game's build-menu tags: a chest that lists the others
            piece.m_craftingStation = workbench;
            // the cost setting (a server owner can change it); if neither it nor the default can be read, the chest's: never free to build
            if (!DHack.Shared.Costs.Apply(piece, Cost.Value, Log) && !DHack.Shared.Costs.Apply(piece, DefaultCost, Log))
                piece.m_resources = source.GetComponent<Piece>().m_resources;
            try { Sprite icon = DHack.Shared.Icon.Make(go, new Vector3(0.5f, 0.45f, -1f)); if (icon != null) piece.m_icon = icon; }
            catch (System.Exception e) { Debug.LogWarning($"{Name}: could not draw the build-menu picture: {e.Message}"); }
            go.AddComponent<LedgerPiece>();
            return go;
        }

        /// <summary>
        /// When this copy unloads: out of the build menu, but still registered, so no area loading before the next copy is up loses its
        /// Ledger Chests, or what is in them (Shared/PieceReload.cs). The next copy replaces it.
        /// </summary>
        internal static void Unregister()
        {
            if (_prefab == null) return;
            GameObject hammer = ObjectDB.instance != null ? ObjectDB.instance.GetItemPrefab("Hammer") : null;
            DHack.Shared.PieceReload.UnloadPiece(_prefab, hammer != null ? hammer.GetComponent<ItemDrop>().m_itemData.m_shared.m_buildPieces : null);
            _prefab = null;
            _holder = null;
            Look.Clear();
        }
    }

    /// <summary>Marks a Ledger Chest (the list shows when one of these is open).</summary>
    public class LedgerPiece : MonoBehaviour { }

    // Opening a Ledger Chest asks its owner's game, as any chest. When that is a player without this mod (the nearest player owns what is
    // around them), nothing answers and it never opens: you take it over first (unless someone has it open). It can hold things (what fits
    // in no chest stays in it), but taking it over is as safe as for any chest nobody has open: every game keeps its copy loaded from the
    // saved contents, so the new owner starts from what the old one saved.
    [HarmonyPatch(typeof(Container), nameof(Container.Interact))]
    internal static class Container_Interact_Ledger
    {
        private static void Prefix(Container __instance, bool hold)
        {
            if (hold || !Plugin.IsLedger(__instance)) return;
            ZNetView v = __instance.GetComponent<ZNetView>();
            if (v == null || !v.IsValid() || v.IsOwner() || v.GetZDO().GetInt(ZDOVars.s_inUse, 0) == 1) return;
            v.ClaimOwnership();
        }
    }

    [HarmonyPatch(typeof(ZNetScene), "Awake")]
    internal static class ZNetScene_Awake
    {
        private static void Postfix(ZNetScene __instance) => Plugin.Register(__instance);
    }

    // Whichever of ZNetScene and ObjectDB wakes second, the piece is registered before any saved one is loaded.
    [HarmonyPatch(typeof(ObjectDB), "Awake")]
    internal static class ObjectDB_Awake
    {
        private static void Postfix() { if (ZNetScene.instance != null) Plugin.Register(ZNetScene.instance); }
    }

    // While you type in the search: your character and the inventory's keys (Tab, E) do not react to the letters.
    [HarmonyPatch(typeof(Player), "TakeInput")]
    internal static class Player_TakeInput
    {
        private static void Postfix(Player __instance, ref bool __result) { if (__instance == Player.m_localPlayer && Plugin.Instance != null && Plugin.Instance.Ledger.Typing) __result = false; }
    }

    [HarmonyPatch(typeof(PlayerController), "TakeInput")]
    internal static class PlayerController_TakeInput
    {
        private static void Postfix(ref bool __result) { if (Plugin.Instance != null && Plugin.Instance.Ledger.Typing) __result = false; }
    }

    [HarmonyPatch(typeof(InventoryGui), "Update")]
    internal static class InventoryGui_Update
    {
        private static void Prefix()
        {
            if (Plugin.Instance == null || !Plugin.Instance.Ledger.Typing) return;
            ZInput.ResetButtonStatus("Use");        // E would close the chest
            ZInput.ResetButtonStatus("Inventory");  // and Tab the inventory
        }
    }

    // ... nor the map (M), the chat (Enter) and other mods' keys, which ask the game whether a text box has the keyboard.
    [HarmonyPatch(typeof(Minimap), nameof(Minimap.InTextInput))]
    internal static class Minimap_InTextInput
    {
        private static void Postfix(ref bool __result) { if (Plugin.Instance != null && Plugin.Instance.Ledger.Typing) __result = true; }
    }
}
